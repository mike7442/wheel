#include <Arduino.h>

// Определяем пины для внешнего UART
#define EXT_UART_RX 16
#define EXT_UART_TX 17

// Создаем объект для внешнего Serial. 
// Цифра 1 означает, что мы используем аппаратный UART1 ESP32
HardwareSerial ExtSerial(1);

void setup() {
  // 1. Инициализируем основной USB Serial (нативный порт S3)
  // Для USB CDC скорость формально не важна, но оставим стандартную
  Serial.begin(115200);
  
  // Небольшая задержка, чтобы операционная система успела "подхватить" USB-порт
  delay(1000); 
  Serial.println("USB Serial готов. Ожидаю данные для отправки на UART1 (TX:17, RX:16)...");

  // 2. Инициализируем внешний UART на пинах 16 и 17
  // Формат: begin(скорость, конфигурация, пин_RX, пин_TX)
  ExtSerial.begin(115200, SERIAL_8N1, EXT_UART_RX, EXT_UART_TX);
  
  Serial.println("Внешний UART инициализирован.");
}

void loop() {
  // === НАПРАВЛЕНИЕ 1: Компьютер (USB) -> Внешнее устройство (UART) ===
  if (Serial.available()) {
    // Читаем ровно один байт, который пришел из USB
    char c = Serial.read();
    
    // Отправляем его во внешний UART ровно в том же виде.
    // Если это буква - уйдет буква. Если это Enter (\r или \n) - уйдет \r или \n.
    ExtSerial.write(c);
  }

  // === НАПРАВЛЕНИЕ 2: Внешнее устройство (UART) -> Компьютер (USB) ===
  // (Я добавил это, потому что в 99% случаев тебе нужно видеть ответ 
  // от устройства, которому ты шлешь команды. Если нужен строго 
  // однонаправленный канал, просто закомментируй этот блок)
  if (ExtSerial.available()) {
    char c = ExtSerial.read();
    Serial.write(c);
  }
}